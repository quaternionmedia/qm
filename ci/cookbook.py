#!/usr/bin/env python3
"""One onboarding page per family, generated from what is true on this disk.

    uv run qm cookbook --write walkthrough/families
    uv run qm cookbook --check walkthrough/families

Generated, because a hand-written onboarding page goes stale first. It is
read by exactly the person least able to notice it is wrong -- somebody new,
who has no way to tell a stale instruction from a current one. So every figure
here comes from `families.json` and from the clones on this disk, and the page
is regenerated by the ordinary command rather than edited.

The picture is drawn, not pasted. Each page carries an SVG of its family,
emitted here from the same data as the prose beside it. A screenshot pasted
into a document is a claim about a moment nobody can re-take;
`records/DRAFT-one-executable-walkthrough.md` is the decision, and this is that
rule applied to a diagram.

What these pages cannot do: tell a reader whether a repository works. They
report what the org has claimed and what the disk shows -- a family, its
members, which carry governance, and which have uncommitted work. A family
with no adopted member gets a page that says it has no governed entry point
rather than inventing one.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAMILIES = ROOT / "families.json"
SEARCH_ROOTS = (ROOT.parent, ROOT.parent.parent)
# What the roster's `paths` are relative to: two directories above this clone,
# as `ci/make_workspace.py` and `ci/estate.py` assume. One convention.
ROSTER_ROOTS = [ROOT.parent.parent]


def git(path: Path, *args: str) -> str:
    try:
        done = subprocess.run(["git", "-C", str(path), *args], capture_output=True,
                              encoding="utf-8", errors="replace", timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return done.stdout.strip() if done.returncode == 0 else ""


def roster_index() -> dict[str, dict]:
    """Every roster entry, keyed by its name and by its reference.

    `families.json` carries a private member as its reference. The loader
    merges `ci/workspace-private.yaml` where it is present, so the entry the
    reference maps to carries the real candidate paths on a machine that
    holds them, and none anywhere else.
    """
    sys.path.insert(0, str(ROOT / "ci"))
    try:
        import roster
        entries = roster.load()
    except Exception:
        return {}
    index: dict[str, dict] = {}
    for entry in entries:
        for key in (entry.get("name"), entry.get("ref")):
            if key:
                index[key] = entry
    return index


def clone_of(name: str, index: dict[str, dict] | None = None) -> Path | None:
    """The clone the roster says, else the bare probe the roster predates.

    The probe alone -- `<root>/<name>` -- reported a member whose clone sits
    at a path only the roster carries as not on this disk, and every private
    member likewise, because a reference is not a directory. A
    second resolver disagreeing with the first is how two views of one disk
    come to say different things. So the roster's candidates go first,
    through the resolver the workspace and the estate use, and the probe
    remains only for a member the roster does not carry at all.
    """
    entry = (roster_index() if index is None else index).get(name)
    if entry is not None:
        sys.path.insert(0, str(ROOT / "ci"))
        from make_workspace import resolve
        found = resolve(entry, ROSTER_ROOTS)
        if found is not None:
            return found
    for root in SEARCH_ROOTS:
        candidate = root / name
        if (candidate / ".git").exists():
            return candidate
    return None


def member_state(name: str, adopted: set[str], index: dict[str, dict] | None = None) -> dict:
    """What the disk says about one member. Never a default that reads as good."""
    clone = clone_of(name, index)
    if clone is None:
        return {"name": name, "on_disk": False, "branch": "-", "dirty": None,
                "last": "-", "adopted": name in adopted}
    dirty = [line for line in git(clone, "status", "--porcelain=v1").splitlines() if line]
    return {
        "name": name,
        "on_disk": True,
        "branch": git(clone, "rev-parse", "--abbrev-ref", "HEAD") or "?",
        "dirty": len(dirty),
        "last": git(clone, "log", "-1", "--format=%cs") or "?",
        "adopted": name in adopted,
    }


def adopted_names() -> set[str]:
    """Repositories governance reaches, which is not only the adopting ones.

    A `project/<name>` branch is how a *project* carries records. The corpus
    itself has none and is not thereby ungoverned -- it is the thing doing the
    governing, and the roster says so with `role: corpus`. Reading only the
    branches printed the corpus as the one member of its own family without
    governance, and sent a newcomer to the second-listed repository instead.
    """
    out = git(ROOT, "for-each-ref", "--format=%(refname:short)",
              "refs/remotes/origin/project")
    names = {line.split("/", 2)[-1] for line in out.splitlines() if line}
    sys.path.insert(0, str(ROOT / "ci"))
    try:
        import roster
        names |= {e.get("name") for e in roster.load()
                  if e.get("role") == "corpus" and e.get("name")}
    except Exception:
        pass
    return names


# One hue per family, for light and dark, so a family keeps its colour on
# every picture. A family missing here draws in the neutral, which is a reason
# to add it rather than a fault. Lowercase throughout: a name is set as it is
# written, never in capitals.
HUES = {
    "performing": ("#a85a0c", "#f2aa4c"),
    "show-control": ("#b3305a", "#f0708f"),
    "instruments": ("#0c7a76", "#43c6bf"),
    "performer-display": ("#5a43b5", "#a693f3"),
    "irl": ("#94551f", "#dd9b63"),
    "infra": ("#55647a", "#98a7bc"),
    "core": ("#2a61bd", "#74a8f6"),
    "games": ("#327c47", "#73c886"),
    "civic": ("#8a3f9e", "#cf8ce0"),
}
NEUTRAL = ("#536075", "#9ba5b7")
SANS = "'IBM Plex Sans',system-ui,-apple-system,'Segoe UI',Roboto,sans-serif"
MONO = "'IBM Plex Mono',ui-monospace,'Cascadia Mono',Consolas,monospace"


def _style(names: list[str]) -> str:
    """The picture's own stylesheet: both themes, every hue it uses.

    An SVG shown as an image cannot inherit the page's colours, so it carries
    a light and a dark palette and picks with the reader's preference.
    """
    def hues(index: int) -> str:
        return "".join(
            f".c-{n}{{fill:{HUES.get(n, NEUTRAL)[index]}}}"
            f".s-{n}{{stroke:{HUES.get(n, NEUTRAL)[index]}}}" for n in sorted(set(names)))
    return (
        "<style>"
        f"text{{font-family:{SANS};fill:#141922}}"
        f".mono{{font-family:{MONO}}}"
        ".muted{fill:#536075}.panel{fill:#f3f4f7;stroke:#d5d9e2}"
        ".card{fill:#ffffff;stroke:#d5d9e2}.track{fill:#e8eaf0}"
        f"{hues(0)}"
        "@media (prefers-color-scheme: dark){"
        "text{fill:#e7eaf1}.muted{fill:#9ba5b7}.panel{fill:#0d1118;stroke:#283143}"
        ".card{fill:#151b25;stroke:#283143}.track{fill:#1c2331}"
        f"{hues(1)}}}"
        "</style>"
    )


def _esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def label(drives: str) -> str:
    """What a family drives, short enough to head a column.

    The phrase before the dash, cut at its first comma: `where a thing runs,
    and how it is reached` heads its column as `where a thing runs`.
    """
    head = drives.split(" — ")[0].replace("**", "").strip()
    return head.split(",")[0].strip()


def wrap(text: str, width: int) -> list[str]:
    """Words into lines of at most `width` characters, a long word alone."""
    lines: list[str] = []
    for word in text.split():
        if lines and len(lines[-1]) + 1 + len(word) <= width:
            lines[-1] += " " + word
        else:
            lines.append(word)
    return lines


def _strip(x: float, y: float, w: float, h: float, name: str, drives: str,
           members: int, governed: int) -> list[str]:
    """One family as a channel strip: its name, what it drives, and a meter
    whose lit share is the share of its members governed."""
    parts = [
        f'<rect class="card" x="{x:.1f}" y="{y}" width="{w:.1f}" height="{h}" rx="6"/>',
        f'<rect class="c-{name}" x="{x:.1f}" y="{y}" width="{w:.1f}" height="5" rx="2"/>',
        f'<text class="mono muted" x="{x + 10:.1f}" y="{y + 24}" '
        f'font-size="{min(11.0, (w - 18) / (0.62 * len(name))):.1f}">{_esc(name)}</text>',
    ]
    for index, line in enumerate(wrap(label(drives), max(6, int((w - 20) / 8.6)))[:3]):
        parts.append(f'<text class="c-{name}" x="{x + 10:.1f}" y="{y + 46 + index * 18}" '
                     f'font-size="15" font-weight="700">{_esc(line)}</text>')
    top, bottom = y + 104, y + h - 50
    segments = max(4, int((bottom - top) // 8))
    lit = round(segments * governed / members) if members else 0
    cx = x + w / 2 - 8
    for index in range(segments):
        sy = bottom - (index + 1) * 8 + 2
        parts.append(f'<rect class="{f"c-{name}" if index < lit else "track"}" '
                     f'x="{cx:.1f}" y="{sy}" width="16" height="6" rx="1"/>')
    parts += [
        f'<text x="{x + 10:.1f}" y="{y + h - 28}" font-size="13" font-weight="700">'
        f'{members} {"member" if members == 1 else "members"}</text>',
        f'<text class="mono muted" x="{x + 10:.1f}" y="{y + h - 12}" font-size="11">'
        f'{governed} governed</text>',
    ]
    return parts


def desk(document: dict, counts: dict[str, tuple[int, int]]) -> str:
    """Every family at once, drawn as a desk of channel strips.

    `counts` is `{family: (members, governed)}`, everyone in a family within
    it included. A family that holds others is a frame around their strips,
    headed by what it drives and who claims it directly.
    """
    by_name = {f["name"]: f for f in document["families"]}
    tops = sorted((f for f in document["families"] if not f.get("within")),
                  key=lambda f: (not f.get("subfamilies"), f["name"]))
    slots = sum(max(1, len(f.get("subfamilies", []))) for f in tops)
    width, pad, gap, frame_gap = 1000, 16, 10, 8
    groups = sum(1 for f in tops if f.get("subfamilies"))
    strip_w = (width - 2 * pad - gap * (slots - 1) - 2 * frame_gap * groups) / slots
    top, full = 16, 300
    inner_top = top + 62
    height = top + full + 44
    names = list(by_name)
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="the QM families, each a column with a meter for the share governed">',
        _style(names),
        f'<rect class="panel" x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" rx="10"/>',
    ]
    x = pad
    for family in tops:
        name = family["name"]
        inner = family.get("subfamilies", [])
        if not inner:
            n, g = counts[name]
            parts += _strip(x, top, strip_w, full, name, family["drives"], n, g)
            x += strip_w + gap
            continue
        span = len(inner) * strip_w + (len(inner) - 1) * gap + 2 * frame_gap
        n, g = counts[name]
        own = family.get("members", [])
        parts += [
            f'<rect class="s-{name}" x="{x:.1f}" y="{top}" width="{span:.1f}" height="{full}" '
            f'rx="8" fill="none" stroke-width="1.5"/>',
            f'<rect class="c-{name}" x="{x:.1f}" y="{top}" width="{span:.1f}" height="5" rx="2"/>',
            f'<text class="mono muted" x="{x + 12:.1f}" y="{top + 24}" font-size="11">{_esc(name)}</text>',
            f'<text class="c-{name}" x="{x + 12:.1f}" y="{top + 46}" font-size="17" '
            f'font-weight="700">{_esc(label(family["drives"]))}</text>',
            f'<text class="mono muted" x="{x + span - 12:.1f}" y="{top + 24}" font-size="11" '
            f'text-anchor="end">{n} in all · {g} governed</text>',
        ]
        if own:
            parts.append(
                f'<text class="mono muted" x="{x + span - 12:.1f}" y="{top + 46}" font-size="11" '
                f'text-anchor="end">its own: {_esc(", ".join(own))}</text>')
        cx = x + frame_gap
        for child in inner:
            cn, cg = counts[child]
            parts += _strip(cx, inner_top, strip_w, top + full - inner_top - frame_gap, child,
                            by_name[child]["drives"], cn, cg)
            cx += strip_w + gap
        x += span + gap
    unstated = len(document.get("unstated", []))
    parts += [
        f'<text class="mono muted" x="{pad}" y="{height - 16}" font-size="11">'
        f'the lit share of a meter is the share governed · a repository in two families '
        f'counts in each · {unstated} rostered '
        f'{"repository states" if unstated == 1 else "repositories state"} no family yet</text>',
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


def svg(family: str, members: list[dict], drives: str = "",
        within: str | None = None) -> str:
    """The family as a picture, drawn from the same data as the prose.

    No font has to be present and no gradient is drawn, and the picture
    carries its own light and dark palette. A diagram nobody can re-generate
    is the thing this file exists to avoid, so it stays small enough to read
    as text.
    """
    row, pad = 26, 16
    head = 72 if drives else 44
    width, height = 560, head + row * len(members) + 34
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="the {family} family and its members">',
        _style([family]),
        f'<rect class="panel" x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" rx="10"/>',
        f'<rect class="c-{family}" x="0.5" y="0.5" width="{width - 1}" height="5" rx="2"/>',
        f'<text class="mono muted" x="{pad}" y="{pad + 14}" font-size="12">{_esc(family)}'
        f'{f" · within {_esc(within)}" if within else ""}</text>',
    ]
    if drives:
        parts.append(f'<text class="c-{family}" x="{pad}" y="{pad + 40}" font-size="20" '
                     f'font-weight="700">{_esc(label(drives))}</text>')
    for index, member in enumerate(members):
        y = head + 8 + index * row
        state = "governed" if member["adopted"] else "not adopted"
        dot = (f'<circle class="c-{family}" cx="{pad + 6}" cy="{y - 4}" r="5"/>'
               if member["adopted"] else
               f'<circle class="s-{family}" cx="{pad + 6}" cy="{y - 4}" r="4.5" '
               f'fill="none" stroke-width="1.5"/>')
        parts += [
            dot,
            f'<text class="mono" x="{pad + 20}" y="{y}" font-size="13">{_esc(member["name"])}</text>',
            f'<text class="mono muted" x="{pad + 260}" y="{y}" font-size="12">{state}</text>',
        ]
    parts += [
        f'<text class="mono muted" x="{pad}" y="{height - 12}" font-size="11">'
        f'● governed   ○ not adopted</text>',
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


def everyone_in(family: dict) -> list[str]:
    """Everyone in a family, the families within it included.

    `all_members` where the seam file carries it, else the family's own
    members, so a family written by hand in a test reads the same way.
    """
    return list(family.get("all_members", family.get("members", [])))


def ancestors_in(name: str, by_name: dict[str, dict]) -> list[str]:
    """Every family `name` sits within, nearest first, as the seam file says."""
    chain: list[str] = []
    current = by_name.get(name, {}).get("within")
    while current and current not in chain:
        chain.append(current)
        current = by_name.get(current, {}).get("within")
    return chain


def everyone_within(name: str, by_name: dict[str, dict]) -> list[str]:
    """Every family inside `name`, at any depth."""
    out: list[str] = []
    pending = list(by_name.get(name, {}).get("subfamilies", []))
    while pending:
        child = pending.pop(0)
        if child not in out:
            out.append(child)
            pending.extend(by_name.get(child, {}).get("subfamilies", []))
    return out


def page(family: dict, states: list[dict], generated_at: str,
         inner: list[dict] = (), also: dict[str, list[str]] | None = None) -> str:
    """One family's page. `states` is everyone in it, the families within it
    included; `inner` describes those families, and `also` names the other
    families a member claims."""
    name = family["name"]
    adopted = [s for s in states if s["adopted"]]
    lines = [
        f"# Cookbook — the `{name}` family",
        "",
        "**This page is generated.** Every figure comes from `families.json` and "
        "from the clones on this disk, and `uv run qm cookbook --check` fails the "
        "build when it stops being true. Do not edit it; edit the roster or the "
        "record and regenerate.",
        "",
        f"**Drives** {family['drives']}",
        "",
    ]
    if family.get("within"):
        outer = family["within"]
        lines += [
            f"**Within** [`{outer}`](./{outer}.md): a member of this family is a "
            f"member of `{outer}` too, without claiming it.",
            "",
        ]
    lines += [
        f"![the {name} family](./{name}.svg)",
        "",
        "## Who is in it",
        "",
        "| member | governed |",
        "|---|---|",
    ]
    for state in states:
        lines.append(
            f"| `{state['name']}` | {'yes' if state['adopted'] else 'no'} |")
    shared = [(s["name"], (also or {}).get(s["name"], [])) for s in states]
    shared = [(member, others) for member, others in shared if others]
    if shared:
        lines += [
            "",
            "Also in another family, because each drives more than one thing:",
            "",
        ]
        lines += [f"- `{member}` — " + ", ".join(f"[`{o}`](./{o}.md)" for o in others)
                  for member, others in shared]
    if inner:
        lines += [
            "",
            "## The families within it",
            "",
            "Everyone in these is in this family as well, and is in the table above.",
            "",
            "| family | drives | members | governed |",
            "|---|---|---|---|",
        ]
        lines += [f"| [`{f['name']}`](./{f['name']}.md) | {f['drives']} | "
                  f"{f['members']} | {f['governed']} |" for f in inner]
    lines += [
        "",
        "## Starting here",
        "",
    ]
    if adopted:
        # The corpus first when it is in this family: it is where the rules are,
        # and a newcomer sent anywhere else reads a consumer before the contract.
        first = next((s["name"] for s in adopted if s["name"] == "qm"),
                     adopted[0]["name"])
        lines += [
            f"{len(adopted)} of {len(states)} members carry governance, so this "
            f"family has a governed entry point. Begin in `{first}`:",
            "",
            "```sh",
            f"cd {first}",
            "uv run qm cowork          # or read AGENTS.md, if this repo has no CLI",
            "```",
            "",
            "A governed member is one with a `project/<name>` branch in the corpus. "
            "Its records live there, not in the repository itself.",
        ]
    else:
        lines += [
            "**No member of this family carries governance yet**, so there is no "
            "governed entry point and this page will not invent one. Reading the "
            "code is the entry point.",
            "",
            "Adopting one is `handbook/forking-a-project.md` — nine steps, taken one "
            "repository at a time, and a decision per repository rather than per "
            "family. Nothing here recommends which; that is the border test in "
            "`records/DRAFT-a-family-is-bordered-by-what-it-drives.md` §2 applied by "
            "somebody who knows what the code does.",
        ]
    lines += [
        "",
        "## What this page deliberately does not carry",
        "",
        "**Anything machine-scoped.** Which branch a clone is on, how many "
        "uncommitted files it has, whether it is on this disk at all — none of "
        "that is here, because this page is committed and those facts differ per "
        "machine and per keystroke. A committed document carrying them drifts "
        "every time somebody edits a file, and a check that fails hourly is one "
        "people learn to rerun rather than read.",
        "",
        "`ci/workspace.yaml` and `status/inventory.yaml` make the same split for "
        "the same reason, with the machine-scoped half in an uncommitted "
        "companion. Run `uv run qm cookbook` with no argument to see this "
        "family's state on the disk you are actually sitting at.",
        "",
        "## What this page cannot tell you",
        "",
        "Whether any of it works. It reports a claim — the family, stated by a "
        "person in the roster — and it does not run a member. A family name is "
        "never a statement that anybody is working on it.",
        "",
        f"*Generated {generated_at} from `families.json`.*",
        "",
    ]
    return "\n".join(lines)


def build(out: Path) -> dict[str, str]:
    document = json.loads(FAMILIES.read_text(encoding="utf-8"))
    adopted = adopted_names()
    entries = roster_index()
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    files: dict[str, str] = {}
    index = [
        "# Cookbook — the families",
        "",
        "One page per family, generated from `families.json` and the clones on this "
        "disk. The families themselves are decided in "
        "`records/DRAFT-a-family-is-bordered-by-what-it-drives.md`; this is the "
        "onboarding view of them.",
        "",
        "![the families, each a column with a meter for the share governed](./families.svg)",
        "",
        "A family within another is listed under it, and its members count "
        "toward both. A repository in two families counts in each.",
        "",
        "| family | within | drives | members | governed |",
        "|---|---|---|---|---|",
    ]
    by_name = {family["name"]: family for family in document["families"]}
    claimed: dict[str, list[str]] = {}
    for family in document["families"]:
        for member in family["members"]:
            claimed.setdefault(member, []).append(family["name"])
    states_of = {
        family["name"]: [member_state(name, adopted, entries) for name in everyone_in(family)]
        for family in document["families"]
    }

    def summary(name: str) -> dict:
        states = states_of[name]
        return {"name": name, "drives": by_name[name]["drives"], "members": len(states),
                "governed": sum(1 for s in states if s["adopted"])}

    for family in document["families"]:
        name = family["name"]
        own = set(everyone_in(family))
        # Another family a member claims, unless it is this one or one this
        # family is within or contains -- those are the same membership.
        related = {name, *ancestors_in(name, by_name), *everyone_within(name, by_name)}
        also = {member: [f for f in claimed.get(member, []) if f not in related]
                for member in own}
        inner = [summary(child) for child in family.get("subfamilies", [])]
        files[f"{name}.md"] = page(family, states_of[name], stamp, inner, also)
        files[f"{name}.svg"] = svg(name, states_of[name], family["drives"],
                                   family.get("within"))

    def rows(name: str) -> list[str]:
        s = summary(name)
        outer = by_name[name].get("within")
        out = [f"| [`{name}`](./{name}.md) | {f'`{outer}`' if outer else '—'} | "
               f"{s['drives']} | {s['members']} | {s['governed']} |"]
        for child in by_name[name].get("subfamilies", []):
            out += rows(child)
        return out

    for family in document["families"]:
        if not family.get("within"):
            index += rows(family["name"])
    files["families.svg"] = desk(document, {
        name: (summary(name)["members"], summary(name)["governed"]) for name in by_name})
    index += [
        "",
        f"`{len(document['unstated'])}` rostered repositories claim no family. That "
        "is *unstated*, not *none* — nobody has answered the question for them, and "
        "a page that listed them as unfamilied would be inventing an answer.",
        "",
        f"*Generated {stamp}.*",
        "",
    ]
    files["README.md"] = "\n".join(index)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("out", nargs="?", default="walkthrough/families")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    out = Path(args.out)
    files = build(out)

    if args.check:
        stale = []
        for name, body in files.items():
            path = out / name
            if not path.is_file():
                stale.append(f"{path}: missing")
            elif _without_stamp(path.read_text(encoding="utf-8")) != _without_stamp(body):
                stale.append(f"{path}: out of date")
        for problem in stale:
            print(f"  {problem}", file=sys.stderr)
        if stale:
            print(f"\ncookbook: {len(stale)} page(s) no longer describe this disk. "
                  f"Regenerate with `uv run qm cookbook --write`.", file=sys.stderr)
            return 1
        print(f"cookbook: {len(files)} page(s) still describe this disk.")
        return 0

    if args.write:
        out.mkdir(parents=True, exist_ok=True)
        for name, body in files.items():
            # newline="\n": see families.py -- a Windows text write is CRLF.
            (out / name).write_text(body, encoding="utf-8", newline="\n")
        print(f"wrote {len(files)} file(s) to {out}")
        return 0

    # No flag: the machine-scoped view. This is the half the committed pages
    # deliberately omit -- it differs per machine and per keystroke, so it is
    # printed and never written, exactly as `inventory-local.json` is kept out
    # of the public inventory.
    document = json.loads(FAMILIES.read_text(encoding="utf-8"))
    adopted = adopted_names()
    entries = roster_index()
    print("This disk, right now. None of it is committed anywhere.")
    print()
    for family in document["families"]:
        states = [member_state(name, adopted, entries) for name in everyone_in(family)]
        absent = [s for s in states if not s["on_disk"]]
        dirty = [s for s in states if s["on_disk"] and s["dirty"]]
        print(f"## {family['name']}")
        for state in states:
            where = ("not on this disk" if not state["on_disk"]
                     else f"{state['branch']:34} {state['dirty']:>3} dirty  {state['last']}")
            print(f"   {'*' if state['adopted'] else ' '} {state['name']:20} {where}")
        notes = []
        if absent:
            notes.append(f"{len(absent)} not on this disk")
        if dirty:
            worst = max(dirty, key=lambda s: s["dirty"])
            notes.append(f"{len(dirty)} with uncommitted work, most in {worst['name']}"
                         f" ({worst['dirty']}) -- it lives in no ref")
        summary = "; ".join(notes) if notes else "every member present, every tree clean"
        print(f"     {summary}")
        print()
    print("`* ` is governed. Read the committed pages for what the org claims; "
          "this is only what is here.")
    return 0


def _without_stamp(text: str) -> str:
    """Compare content, not the date it was generated.

    The stamp moves every day and nothing else does, so comparing it would make
    the check fail daily for no reason -- a check that cries wolf is one people
    learn to rerun rather than read.
    """
    return "\n".join(line for line in text.splitlines()
                     if not line.startswith("*Generated "))


if __name__ == "__main__":
    raise SystemExit(main())
